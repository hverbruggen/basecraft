//! Real engines and real directory listings for registered tree and matrix runs.
use basecraft_ops::records::AlignmentLinkExt;
mod common;

use std::path::Path;

use basecraft_ops::{Session, analysis_store::ArtifactRun, input_evidence, records};
use basecraft_protocol::Op;
use serde_json::{Value, json};

const ALIGNMENT: &str = ">a\nACGTACGTACGTACGTACGTACGT\n>b\nACGTACGTTCGTACGTACGTACGT\n>c\nTCGTACGTACGTACGTACGTACGA\n>d\nTCGTACGTTCGTACGTACGTACGA\n";

fn listing(root: &Path, run: &Path, label: &str) {
    println!(
        "{label}: visible={:?}; hidden={:?}",
        common::names(root),
        common::names(run)
    );
}

fn matrix(session: &Session, doc: basecraft_ops::DocId, model: &str, output: &str) -> Value {
    json!({"operation":"basecraft.distance/matrix@1","inputs":{"alignment":common::document(session, doc)},
        "parameters":{"model":model},"destinations":{"artifacts/distances.tsv":output}})
}

#[test]
fn matrix_reference_generated_failure_move_and_export_use_the_common_store() {
    let parent = tempfile::tempdir().unwrap();
    let root = parent.path().join("working");
    std::fs::create_dir(&root).unwrap();
    let source = root.join("source.afa");
    std::fs::write(&source, ALIGNMENT).unwrap();
    let mut session = Session::recoverable(&root).unwrap();
    let doc = session.open(&source).unwrap();
    let registry = common::bundled();
    let output = root.join("matrix.tsv");
    let clean = common::run_in(&registry, &mut session, |s| {
        matrix(s, doc, "p", "matrix.tsv")
    });
    common::assert_completed(&clean);
    let run = ArtifactRun::for_result(&output)
        .unwrap()
        .expect("matrix must be bound to hidden storage");
    assert_eq!(run, common::evidence(&clean));
    assert_eq!(
        common::names(&root),
        [".basecraft", "matrix.tsv", "source.afa"]
    );
    common::member(&clean, "distances.tsv.distances.bin");
    common::member(&clean, "distances.tsv.run.json");
    // A clean document is referenced in place: no copy of its bytes is kept.
    assert!(!run.join("submitted.fasta").exists());
    assert!(!run.join("preserved-input").exists());
    let input = input_evidence::read_input(&run).unwrap();
    assert_eq!(
        input.state,
        basecraft_protocol::input_records::EvidenceState::Referenced
    );
    assert_eq!(
        input.source.unwrap().hash,
        basecraft_io::hash_file(&source).unwrap()
    );
    assert_eq!(records::verify(&output).unwrap(), Vec::<String>::new());
    listing(&root, &run, "matrix-clean");

    session
        .apply(
            doc,
            Op::AlnReplace {
                row: 0,
                start: 0,
                end: 1,
                residues: "T".into(),
            },
        )
        .unwrap();
    let dirty_output = root.join("dirty.tsv");
    let dirty = common::run_in(&registry, &mut session, |s| {
        matrix(s, doc, "p", "dirty.tsv")
    });
    common::assert_completed(&dirty);
    let dirty_run = ArtifactRun::for_result(&dirty_output).unwrap().unwrap();
    // Unsaved edits are submitted as retained generated bytes.
    let input = input_evidence::read_input(&dirty_run).unwrap();
    assert_eq!(
        input.state,
        basecraft_protocol::input_records::EvidenceState::Generated
    );
    assert!(input.source.is_none());
    let generated = dirty_run.join("submitted.fasta");
    assert_eq!(
        input.submitted_hash,
        basecraft_io::hash_file(&generated).unwrap()
    );
    assert!(
        std::fs::read_to_string(&generated)
            .unwrap()
            .starts_with(">a\nTCGT")
    );
    assert_eq!(std::fs::read_to_string(&source).unwrap(), ALIGNMENT);
    listing(&root, &dirty_run, "matrix-dirty");

    // Parameters the descriptor rejects are refused before anything runs.
    let refused = common::refused_in(&registry, &mut session, |s| {
        matrix(s, doc, "unsupported", "failed.tsv")
    });
    println!("unsupported model refused: {refused}");
    assert!(!root.join("failed.tsv").exists());
    assert_eq!(
        common::names(&root),
        [".basecraft", "dirty.tsv", "matrix.tsv", "source.afa"]
    );
    assert!(
        basecraft_ops::records::replay(session.recovery_root())
            .unwrap()
            .ok()
    );
    drop(session);
    std::fs::write(&source, ALIGNMENT.replace("ACGT", "TCGT")).unwrap();
    assert_ne!(records::verify(&output).unwrap(), Vec::<String>::new());
    std::fs::remove_file(&source).unwrap();
    assert_ne!(records::verify(&output).unwrap(), Vec::<String>::new());
    std::fs::write(&source, ALIGNMENT).unwrap();

    let moved = parent.path().join("moved");
    std::fs::rename(&root, &moved).unwrap();
    let output = moved.join("matrix.tsv");
    assert_eq!(records::verify(&output).unwrap(), Vec::<String>::new());
    let package = parent.path().join("export");
    records::package(&output, &package).unwrap();
    std::fs::rename(&moved, parent.path().join("unavailable")).unwrap();
    assert_eq!(
        records::verify(&package.join("matrix.tsv")).unwrap(),
        Vec::<String>::new()
    );
    println!("matrix-export: {:?}", common::names(&package));
}

#[test]
fn ordinary_tree_and_forest_routes_keep_only_scientific_results_visible() {
    let registry = common::bundled();
    for (plugin, method, alignment, expected) in [
        ("distance", "sorted", ALIGNMENT, vec!["result.nwk"]),
        ("distance", "upgma", ALIGNMENT, vec!["result.nwk"]),
        (
            "distance",
            "njstar",
            ">a\nAAA---\n>b\nAAT---\n>c\n---CCC\n>d\n---CCT\n",
            vec![
                "result.component-1.nwk",
                "result.component-2.nwk",
                "result.nwk",
            ],
        ),
        ("fasttree", "", ALIGNMENT, vec!["result.nwk"]),
        ("iqtree", "", ALIGNMENT, vec!["result.nwk"]),
    ] {
        let parent = tempfile::tempdir().unwrap();
        let root = parent.path();
        let source = root.join("source.afa");
        std::fs::write(&source, alignment).unwrap();
        let mut session = Session::new(root);
        let doc = session.open(&source).unwrap();
        let operation = format!("basecraft.{plugin}/tree@1");
        // Each tool's own model name; FastTree keeps its standard model.
        let mut parameters = json!({"threads":1,"seed":71});
        match plugin {
            "iqtree" => parameters["model"] = json!("JC"),
            "fasttree" => {}
            _ => parameters["model"] = json!("p"),
        }
        if !method.is_empty() {
            parameters["method"] = json!(method);
        }
        let parameters = common::declared_only(&registry, &operation, &parameters);
        let outcome = common::run_in(&registry, &mut session, |s| {
            json!({"operation":operation,"inputs":{"alignment":common::document(s, doc)},
                "parameters":parameters,"destinations":{"artifacts/tree.nwk":"result.nwk"}})
        });
        common::assert_completed(&outcome);
        let run = common::evidence(&outcome);
        assert!(!run.join("submitted.fasta").exists());
        assert!(!run.join("preserved-input").exists());
        let execution = common::read_json(&run.join("execution.json"));
        assert!(
            execution["tool"]["version"]
                .as_str()
                .is_some_and(|s| !s.is_empty() && s != "unknown"),
            "{execution}"
        );
        let mut visible = vec![".basecraft", "source.afa"];
        visible.extend(expected.iter().copied());
        visible.sort_unstable();
        assert_eq!(common::names(root), visible);
        for name in expected {
            let tree = root.join(name);
            assert_eq!(ArtifactRun::for_result(&tree).unwrap().unwrap(), run);
            let id = session.open(&tree).unwrap();
            let link = basecraft_ops::records::AlignmentLink::read(&tree).unwrap();
            assert_eq!(link.source, source);
            assert!(
                link.checked_snapshot(&tree, session.tree(id).unwrap())
                    .is_ok()
            );
            session.save(id, None).unwrap();
            assert!(basecraft_ops::files::tree_sidecar(&tree).starts_with(&run));
        }
        assert_eq!(common::names(root), visible);
        listing(root, &run, &format!("{plugin}-{method}"));
        if plugin == "iqtree" {
            common::member(&outcome, "tree.nwk.iqtree");
            common::member(&outcome, "tree.nwk.log");
            assert_eq!(
                common::read_json(&common::member(&outcome, "tree.nwk.run.json"))["seed"],
                71
            );
        }
    }
}
