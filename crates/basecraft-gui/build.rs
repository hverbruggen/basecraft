//! Compiles the RHI shaders with Qt's `qsb` into a C++ header, then builds
//! the cxx-qt bridge, the C++ draw items and the QML module.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use cxx_qt_build::{CxxQtBuilder, QmlModule};

fn qmake_query(var: &str) -> String {
    let qmake = std::env::var("QMAKE").unwrap_or_else(|_| "qmake6".into());
    let out = Command::new(&qmake)
        .args(["-query", var])
        .output()
        .unwrap_or_else(|e| panic!("running {qmake}: {e}"));
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

fn qt_host_bins() -> PathBuf {
    PathBuf::from(qmake_query("QT_HOST_BINS"))
}

fn compile_shaders(out_dir: &Path) {
    let qsb = qt_host_bins().join("qsb");
    let mut header =
        String::from("// Generated by build.rs from shaders/*.{vert,frag}.\n#pragma once\n");
    for (name, file) in [
        ("instance_vert", "shaders/instance.vert"),
        ("instance_frag", "shaders/instance.frag"),
    ] {
        println!("cargo::rerun-if-changed={file}");
        let target = out_dir.join(format!("{name}.qsb"));
        let status = Command::new(&qsb)
            .args([
                "--glsl",
                "100 es,120,150",
                "--hlsl",
                "50",
                "--msl",
                "12",
                "-o",
            ])
            .arg(&target)
            .arg(file)
            .status()
            .unwrap_or_else(|e| panic!("running {}: {e}", qsb.display()));
        assert!(status.success(), "qsb failed for {file}");
        let bytes = std::fs::read(&target).expect("qsb output");
        let _ = write!(header, "static const unsigned char basecraft_{name}[] = {{");
        for (i, b) in bytes.iter().enumerate() {
            if i % 20 == 0 {
                header.push('\n');
            }
            let _ = write!(header, "{b},");
        }
        header.push_str("\n};\n");
    }
    std::fs::create_dir_all(out_dir.join("shaders")).expect("shader dir");
    std::fs::write(out_dir.join("shaders/basecraft_shaders.h"), header)
        .expect("write shader header");
}

fn main() {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    compile_shaders(&out_dir);
    // The versioned QtGui directory holds <rhi/qrhi.h>; CMake would add it
    // through Qt6::GuiPrivate.
    let gui_private = PathBuf::from(qmake_query("QT_INSTALL_HEADERS"))
        .join("QtGui")
        .join(qmake_query("QT_VERSION"));
    let shader_dir = out_dir.join("shaders");
    let builder = CxxQtBuilder::new_qml_module(QmlModule::new("Basecraft").qml_files([
        "qml/Main.qml",
        "qml/FeatureEditor.qml",
        "qml/DocumentView.qml",
    ]))
    .qt_module("Quick")
    .files(["src/bridge.rs"])
    .cpp_file("cpp/instanceview.h")
    .cpp_file("cpp/instanceview.cpp")
    .cpp_file("cpp/filetreemodel.h")
    .cpp_file("cpp/filetreemodel.cpp");
    // SAFETY: not a memory-safety concern; cxx-qt marks this unsafe because
    // its cc::Build may change between minor versions.
    let builder = unsafe {
        builder.cc_builder(|cc| {
            cc.include(&shader_dir);
            cc.include(&gui_private);
            cc.include(gui_private.join("QtGui"));
            // GCC 16 warns about Qt's own headers.
            cc.flag_if_supported("-Wno-sfinae-incomplete");
        })
    };
    builder.build();
}
